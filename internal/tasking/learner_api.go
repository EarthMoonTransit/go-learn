package tasking

import (
	"bytes"
	"go/ast"
	"go/build"
	"go/build/constraint"
	"go/format"
	"go/parser"
	"go/token"
	"path/filepath"
	"sort"
)

const learnerAPIPath = "subject/learn_api.go"

// learnerTestAPI exports declarations, never implementation bodies or values.
// Complex APIs retain the existing checker-only workflow until their public
// declaration contract can be represented without exposing private structure.
func learnerTestAPI(paths []string) ([]byte, error) {
	fileset := token.NewFileSet()
	var signatures []string
	names := map[string]bool{}
	packageName := ""
	for _, path := range paths {
		content, err := readRegularFile(path, 8<<20)
		if err != nil {
			return nil, err
		}
		portable, err := portableAPIFile(path, content)
		if err != nil {
			return nil, err
		}
		if !portable {
			return nil, nil
		}
		file, err := parser.ParseFile(fileset, path, content, 0)
		if err != nil {
			return nil, err
		}
		packageName = file.Name.Name
		for _, declaration := range file.Decls {
			switch declaration := declaration.(type) {
			case *ast.FuncDecl:
				if !declaration.Name.IsExported() {
					continue
				}
				if declaration.Recv != nil || !simpleAPIType(declaration.Type) || names[declaration.Name.Name] {
					return nil, nil
				}
				names[declaration.Name.Name] = true
				clone := *declaration
				functionType := *declaration.Type
				clone.Type = &functionType
				// The shared API fingerprint intentionally remains unchanged.
				// Normalize callback names only in this editor-only AST.
				ast.Inspect(clone.Type, func(node ast.Node) bool {
					if function, ok := node.(*ast.FuncType); ok {
						function.Params = normalizedFieldList(function.Params)
						function.Results = normalizedFieldList(function.Results)
					}
					return true
				})
				signatures = append(signatures, normalizedFunctionSignature(fileset, &clone))
			case *ast.GenDecl:
				for _, spec := range declaration.Specs {
					switch spec := spec.(type) {
					case *ast.TypeSpec:
						if spec.Name.IsExported() || simpleAPIName(spec.Name.Name) {
							return nil, nil
						}
					case *ast.ValueSpec:
						for _, name := range spec.Names {
							if name.IsExported() {
								return nil, nil
							}
						}
					}
				}
			}
		}
	}
	if len(signatures) == 0 {
		return nil, nil
	}
	sort.Strings(signatures)
	var output bytes.Buffer
	output.WriteString("// Code generated by Go Learn. DO NOT EDIT.\n")
	output.WriteString("// Editor declarations only. Run learn check or learn complete to verify tests.\n")
	output.WriteString("package " + packageName + "\n\n")
	for _, signature := range signatures {
		output.WriteString(signature + " { panic(\"Editor declaration only; use learn check or learn complete.\") }\n")
	}
	return format.Source(output.Bytes())
}

func portableAPIFile(path string, content []byte) (bool, error) {
	for _, line := range bytes.Split(content, []byte{'\n'}) {
		text := string(bytes.TrimSpace(line))
		if constraint.IsGoBuild(text) || constraint.IsPlusBuild(text) {
			return false, nil
		}
	}
	// Let Go recognize OS/architecture filename suffixes using its own lists.
	// A neutral target excludes every recognized platform-specific filename.
	context := build.Default
	context.GOOS, context.GOARCH = "go-learn-neutral-os", "go-learn-neutral-arch"
	return context.MatchFile(filepath.Dir(path), filepath.Base(path))
}

func simpleAPIName(name string) bool {
	switch name {
	case "bool", "string", "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr", "float32", "float64",
		"complex64", "complex128", "byte", "rune", "error", "any":
		return true
	default:
		return false
	}
}

func simpleAPIFields(fields *ast.FieldList) bool {
	if fields == nil {
		return true
	}
	for _, field := range fields.List {
		if !simpleAPIType(field.Type) {
			return false
		}
	}
	return true
}

func simpleAPIType(expression ast.Expr) bool {
	switch expression := expression.(type) {
	case *ast.Ident:
		return simpleAPIName(expression.Name)
	case *ast.ArrayType:
		if expression.Len != nil {
			literal, ok := expression.Len.(*ast.BasicLit)
			if !ok || literal.Kind != token.INT {
				return false
			}
		}
		return simpleAPIType(expression.Elt)
	case *ast.MapType:
		return simpleAPIType(expression.Key) && simpleAPIType(expression.Value)
	case *ast.StarExpr:
		return simpleAPIType(expression.X)
	case *ast.Ellipsis:
		return simpleAPIType(expression.Elt)
	case *ast.ChanType:
		return simpleAPIType(expression.Value)
	case *ast.FuncType:
		return expression.TypeParams == nil && simpleAPIFields(expression.Params) && simpleAPIFields(expression.Results)
	case *ast.InterfaceType:
		return expression.Methods == nil || len(expression.Methods.List) == 0
	default:
		return false
	}
}
