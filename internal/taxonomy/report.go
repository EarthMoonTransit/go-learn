package taxonomy

import (
	"bytes"
	"fmt"
	"strings"

	"go-practice-bank/internal/safeio"
)

const ReportPath = "reports/taxonomy-v4-migration.md"

// MigrationReport reports the actual finite metadata transition. Numeric bank
// occurrences and semantic evidence coverage are deliberately separate.
func MigrationReport(root string) ([]byte, error) {
	t, err := ValidateTransition(root)
	if err != nil {
		return nil, err
	}
	_, current, err := readImmutableDocument(root, "curriculum/skills.yaml")
	if err != nil {
		return nil, err
	}
	all, err := skills(current)
	if err != nil {
		return nil, err
	}
	scopes, err := readCoverageScopes(root, all)
	if err != nil {
		return nil, err
	}
	active, deprecated, primary, total := 0, 0, 0, 0
	for _, s := range all {
		if s["status"] == "deprecated" {
			deprecated++
			continue
		}
		active++
		minimum, ok := s["minimum_occurrences"].(map[string]any)
		if !ok {
			return nil, fmt.Errorf("taxonomy report: invalid minimum for %v", s["id"])
		}
		p, okp := minimum["primary"].(int)
		n, okn := minimum["total"].(int)
		if !okp || !okn {
			return nil, fmt.Errorf("taxonomy report: invalid minimum for %v", s["id"])
		}
		primary += p
		total += n
	}
	var b strings.Builder
	b.WriteString("# Taxonomy v4 additive migration\n\nGenerated by `taxonomy-report`; design: `" + Decision + "`.\n\n")
	fmt.Fprintf(&b, "The v3 baseline comes from `curriculum/skills.yaml` at commit `%s` (SHA-256 `%s`). Its byte-identical retained snapshot is `%s`.\n\n", t.Baseline.SourceCommit, t.Baseline.TaxonomySHA256, t.Baseline.TaxonomyPath)
	fmt.Fprintf(&b, "All **%d** old IDs are preserved: **%d** active teaching contracts and **%d** deprecated non-assignable stubs. Only taxonomy-version fields advance.\n\n", len(t.Entries), t.Baseline.ActiveCount, t.Baseline.DeprecatedCount)
	fmt.Fprintf(&b, "The live v4 taxonomy has **%d active skills**, **%d deprecated stubs**, and **%d total IDs**. Full-bank numeric requirements are **%d primary / %d total occurrences**; the ready-task target stays **350–500**.\n\n", active, deprecated, len(all), primary, total)
	fmt.Fprintf(&b, "The explicit versioned `%s` classification contains **%d foundation / %d specialist skills** and is closed under foundation prerequisites. It classifies every active ID exactly once; missing, duplicate, unknown, deprecated or unapproved assignments are errors.\n\n", ScopePath, len(scopes.Foundation), len(scopes.Specialist))
	b.WriteString("These are bank requirements, not actual task counts, required learner completions, or human mastery. Required modes/distinct exercise types and observable outcomes remain separate semantic review obligations. This migration does not implement scoped numeric coverage or a recursion assessment runner.\n\n## Explicit additions\n\n| ID | Canonical teaching-contract SHA-256 |\n|---|---|\n")
	for _, entry := range t.Additions {
		fmt.Fprintf(&b, "| `%s` | `%s` |\n", entry.ID, entry.ContractSHA256)
	}
	b.WriteString("\nRecursion implementation/debugging authoring remains blocked until the independently reviewed finite assessment contract and disposable proof required by ADR0031 exist. No new ID receives retroactive task or completion credit.\n\n## Reviewed v3 document compatibility\n\n| Original path | Immutable snapshot | Exact bytes SHA-256 | Referenced IDs |\n|---|---|---|---:|\n")
	for _, r := range t.ReviewedDocuments {
		fmt.Fprintf(&b, "| `%s` | `%s` | `%s` | %d |\n", r.Path, r.SnapshotPath, r.SHA256, len(r.SkillIDs))
	}
	b.WriteString("\nOriginal version, review decisions and coverage-ineligible evidence are retained. Historical v2-to-v3 validation and v3 reports use the frozen v3 target. Unknown versions, changed old contracts and unreviewed compatibility bytes fail closed. Task manifests, routes, learner workspaces and completion history are not migrated.\n")
	return []byte(b.String()), nil
}

func CheckMigrationReport(root string) error {
	expected, err := MigrationReport(root)
	if err != nil {
		return err
	}
	actual, err := safeio.ReadFile(root, ReportPath, 1<<20)
	if err != nil {
		return fmt.Errorf("taxonomy migration report: %w", err)
	}
	if !bytes.Equal(actual, expected) {
		return fmt.Errorf("%s is stale; run taxonomy-report", ReportPath)
	}
	return nil
}
